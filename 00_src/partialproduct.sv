module partialproduct (
  input  logic [31:0] i_a,
  input  logic        i_p1,
  input  logic        i_n1,
  input  logic        i_p2,
  input  logic        i_n2,
  input  logic        i_negc,
  output logic [32:0] o_pp,
  output logic        o_cy
);

//====================================DECLARATION==============================================================//

  logic [32:0] a_temp;
  logic [32:0] a2_temp;
  logic [32:0] o_pp_temp;

//============================================================================================================//

//====================================COMBINATIONAL LOGIC=====================================================//

  assign a_temp     = {i_a[31], i_a};
  assign a2_temp    = {i_a, 1'b0};
  assign o_pp_temp  = ({33{i_p1}} & a_temp) | ({33{i_n1}} & ~a_temp) | ({33{i_p2}} & a2_temp) | ({33{i_n2}} & ~a2_temp);
  assign o_pp[32:1] = o_pp_temp[32:1];

//============================================================================================================//

//==========================================MODULE============================================================//

  halfadder u_ha_lsb (.i_a(o_pp_temp[0]), .i_b(i_negc), .o_sum(o_pp[0]), .o_carry(o_cy));

//============================================================================================================//

endmodule