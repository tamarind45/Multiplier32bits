module signextension_32b (
  input  logic [527:0] i_pp,
  output logic [494:0] o_pp,
  output logic [ 31:0] o_pp15,
  output logic [ 15:0] o_k_const
);

//====================================DECLARATION==============================================================//

  // o_pp[494:0]     : 15 hàng đầu (k = 0..14), mỗi hàng 33 bit đã đảo bit dấu MSB
  // o_pp15[31:0]    : Hàng cuối (k = 15), chỉ giữ 32 bit thấp (bỏ bit dấu ở cột 62)
  // o_k_const[15:0] : 16 bit '1' hằng số K tại cột 32 và các cột lẻ 33, 35, ..., 61

//============================================================================================================//

//====================================COMBINATIONAL LOGIC=====================================================//

  assign o_pp[ 32:  0] = {~i_pp[ 32], i_pp[ 31:  0]};
  assign o_pp[ 65: 33] = {~i_pp[ 65], i_pp[ 64: 33]};
  assign o_pp[ 98: 66] = {~i_pp[ 98], i_pp[ 97: 66]};
  assign o_pp[131: 99] = {~i_pp[131], i_pp[130: 99]};
  assign o_pp[164:132] = {~i_pp[164], i_pp[163:132]};
  assign o_pp[197:165] = {~i_pp[197], i_pp[196:165]};
  assign o_pp[230:198] = {~i_pp[230], i_pp[229:198]};
  assign o_pp[263:231] = {~i_pp[263], i_pp[262:231]};
  assign o_pp[296:264] = {~i_pp[296], i_pp[295:264]};
  assign o_pp[329:297] = {~i_pp[329], i_pp[328:297]};
  assign o_pp[362:330] = {~i_pp[362], i_pp[361:330]};
  assign o_pp[395:363] = {~i_pp[395], i_pp[394:363]};
  assign o_pp[428:396] = {~i_pp[428], i_pp[427:396]};
  assign o_pp[461:429] = {~i_pp[461], i_pp[460:429]};
  assign o_pp[494:462] = {~i_pp[494], i_pp[493:462]};

  assign o_pp15        = i_pp[526:495];
  assign o_k_const     = 16'hFFFF;

//============================================================================================================//

endmodule